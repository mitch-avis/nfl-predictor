"""Render ``INVENTORY.md`` from the inventory payload."""

from __future__ import annotations

import re
from collections import Counter, defaultdict
from typing import Any

from report_text import season_ranges, table

CLASSES = ("matched", "different", "missing")
RATING_KINDS = (
    "ratings",
    "ratings_by_week",
    "rating_ranges",
    "rating_pairs",
    "rating_ranges_by_week",
    "team_prior",
    "qb_ratings",
    "qb_ratings_by_week",
    "qb_rating_ranges",
    "qb_rating_pairs",
    "qb_rating_ranges_by_week",
)


def render(payload: dict[str, Any]) -> str:
    """Return the Markdown inventory."""
    out: list[str] = []
    w = out.append
    w("<!-- markdownlint-disable -->")
    w("<!-- Generated file: wide tables and verbatim code cells; lint the generator. -->")
    w("")
    w("# nfl-sos-ratings port inventory (generated)")
    w("")
    w("Generated by `.venv/bin/python .agents/sos_port/inventory.py`; do not edit by hand. Every")
    w("list here is found by the script; the classifications come from `mapping.yaml` and are")
    w("checked as they are applied. The full data is in `inventory.json` beside this file.")
    w("")
    _summary(payload, w)
    _sources(payload, w)
    _kinds(payload, w)
    _ratings(payload, w)
    _columns(payload, w)
    _registry(payload, w)
    _web(payload, w)
    _rules(payload, w)
    w("## Failures")
    w("")
    if not payload["failures"]:
        w("None.")
    for failure in payload["failures"]:
        w(f"- {failure['what']}: {failure['detail']}")
    w("")
    return "\n".join(out)


def _counts(rows: list[dict[str, Any]], key: str = "classification") -> str:
    """Render class counts as ``matched 3, different 2, missing 1``."""
    counter = Counter(row[key] for row in rows)
    return ", ".join(f"{name} {counter.get(name, 0)}" for name in CLASSES)


def _summary(payload: dict[str, Any], w: Any) -> None:
    """Write the headline counts."""
    columns = payload["columns"]
    checkout = payload["sos_checkout"]
    kinds = payload["kinds"]
    completed = [kind for kind, seasons in kinds.items() if min(seasons) < 2026]  # noqa: PLR2004
    current = sorted(set(kinds) - set(completed))
    partial = [c for c in columns if len(c["seasons"]) != len(kinds[c["kind"]])]
    metrics = payload["registry"]["metrics"]
    entities = Counter(metric["entity"] for metric in metrics)
    sources = payload["sources"]["classified"]
    web = payload["web"]["classified"]
    w("## Summary")
    w("")
    changed = checkout["output_code_changed_since_build"] or "nothing"
    w(
        f"- nfl-sos-ratings at `{checkout['frozen_commit'][:7]}` (checkout HEAD "
        f"`{checkout['checkout_head'][:7]}`); its data built from "
        f"`{checkout['data_build_commit']}`; output code changed since: {changed}."
    )
    w(
        f"- Output file kinds: {len(kinds)} ({len(completed)} per completed season, read over "
        f"{season_ranges(kinds[completed[0]]) if completed else '-'}; {len(current)} only for "
        f"the season in progress: {', '.join(current) or 'none'})."
    )
    w(f"- Output columns (kind and column): {len(columns)}; {_counts(columns)}.")
    w(f"- Columns present in only some seasons of their kind: {len(partial)}.")
    w(
        f"- Distinct column names: {len({c['column'] for c in columns})}; resolved through its "
        f"registry: {len(columns)} of {len(columns)}."
    )
    w(
        f"- Registry metrics: {len(metrics)} (team {entities.get('team', 0)}, quarterback "
        f"{entities.get('qb', 0)}); metrics no output file uses: "
        f"{sum(1 for m in metrics if not m['output_columns'])}."
    )
    w(
        f"- Data sources it loads: {len(payload['sources']['sos'])}; {_counts(sources, 'class')}. "
        f"This repository's: {len(payload['sources']['here'])}."
    )
    w(
        f"- Web items (API endpoints, pages, page components): {len(payload['web']['sos'])}; "
        f"{_counts(web, 'class')}. This app's: {len(payload['web']['here'])}."
    )
    w(f"- Classification rules: {len(payload['rules'])}.")
    w(f"- Failures: {len(payload['failures'])}.")
    w("")


def _sites(rows: list[dict[str, Any]]) -> str:
    """Render load sites as ``path:line (function)``."""
    return "; ".join(f"`{r['path']}:{r['line']}` ({r['function']})" for r in rows)


def _sources(payload: dict[str, Any], w: Any) -> None:
    """Write the data sources of both repositories."""
    w("## Data sources")
    w("")
    w("Found in each repository's Python source: nflreadpy `load_*` calls, network fetches, web")
    w("addresses, and data files named under the data directory.")
    w("")
    w("### nfl-sos-ratings")
    w("")
    sos = payload["sources"]["sos"]
    rows = [
        [
            f"`{row['key']}`",
            _sites(sos[row["key"]]),
            row["class"],
            ", ".join(f"`{h}`" for h in row["here"]) or "-",
            row["phase"] or "-",
            row["note"],
        ]
        for row in payload["sources"]["classified"]
    ]
    for line in table(["source", "where", "class", "here", "phase", "note"], rows):
        w(line)
    w("")
    w("### This repository")
    w("")
    here = payload["sources"]["here"]
    for line in table(["source", "where"], [[f"`{k}`", _sites(v)] for k, v in here.items()]):
        w(line)
    w("")


def _kinds(payload: dict[str, Any], w: Any) -> None:
    """Write one row per output kind."""
    by_kind: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for column in payload["columns"]:
        by_kind[column["kind"]].append(column)
    w("## Output files")
    w("")
    rows = []
    for kind, seasons in payload["kinds"].items():
        found = by_kind[kind]
        counter = Counter(c["classification"] for c in found)
        rows.append(
            [
                f"`{kind}`",
                season_ranges(seasons),
                len(found),
                *(counter.get(name, 0) for name in CLASSES),
            ]
        )
    for line in table(["kind", "seasons read", "columns", *CLASSES], rows):
        w(line)
    w("")


def _column_rows(columns: list[dict[str, Any]]) -> list[list[object]]:
    """Return the table rows for a list of classified columns."""
    return [
        [
            f"`{c['column']}`",
            f"`{c['base']}`"
            + (f" ({c['prefix']}...{c['suffix']})" if c["prefix"] or c["suffix"] else ""),
            c["code_source"] or c["registry_source"],
            c["classification"],
            ", ".join(f"`{h}`" for h in c["here"]) or "-",
            f"`{c['rule']}`",
        ]
        for c in columns
    ]


HEADER = [
    "column",
    "base metric (affixes)",
    "source there",
    "class",
    "here",
    "rule (phase and note: Column rules)",
]


def _ratings(payload: dict[str, Any], w: Any) -> None:
    """Write its rating outputs against this repository's strength and quarterback columns."""
    columns = [c for c in payload["columns"] if c["kind"] in RATING_KINDS]
    named: Counter[str] = Counter()
    for column in payload["columns"]:
        for ref in column["here"]:
            source, _, names = ref.partition(":")
            named.update(f"{source}:{name}" for name in re.split(r"\s+[-+*/]\s+", names.strip()))
    catalog = payload["here_catalog"]
    w("## Ratings")
    w("")
    w("Its rating files (team and quarterback ratings, weekly histories, rank ranges, pairs and")
    w("the team prior), as classified in the column tables below, then this repository's strength")
    w("snapshot and quarterback columns with how many of its columns name each.")
    w("")
    w(f"- Rating columns: {len(columns)}; {_counts(columns)}.")
    w("")
    for line in table(
        ["kind", *HEADER],
        [[f"`{c['kind']}`", *row] for c, row in zip(columns, _column_rows(columns), strict=True)],
    ):
        w(line)
    w("")
    ours = [f"strength:{name}" for name in catalog["strength"]]
    ours += [
        f"dataset:{name}"
        for name in catalog["dataset"]
        if name.startswith(("qb_", "sos_")) and not name.endswith("_diff")
    ]
    rows = [[f"`{name}`", named.get(name, 0)] for name in ours]
    for line in table(["this repository's column", "its columns naming it"], rows):
        w(line)
    w("")


def _columns(payload: dict[str, Any], w: Any) -> None:
    """Write every classified column, one table per kind."""
    by_kind: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for column in payload["columns"]:
        by_kind[column["kind"]].append(column)
    w("## Columns by file kind")
    w("")
    for kind in payload["kinds"]:
        if kind in RATING_KINDS:
            continue
        found = by_kind[kind]
        w(f"### `{kind}` ({len(found)}; {_counts(found)})")
        w("")
        for line in table(HEADER, _column_rows(found)):
            w(line)
        w("")


def _registry(payload: dict[str, Any], w: Any) -> None:
    """Write its metric registry entries."""
    registry = payload["registry"]
    w("## Metric registry")
    w("")
    w(
        f"Prefix rules: {', '.join(f'`{p}`' for p in registry['prefix_rules'])}. Suffix rules: "
        f"{', '.join(f'`{s}`' for s in registry['suffix_rules'])}."
    )
    w("")
    rows = [
        [
            f"`{m['name']}`",
            m["entity"],
            m["category"],
            m["subcategory"] or "-",
            m["shape"],
            m["source"],
            m["since"] or "-",
            m["duplicate_of"] or "-",
            m["output_columns"],
        ]
        for m in registry["metrics"]
    ]
    header = [
        "metric",
        "entity",
        "category",
        "subcategory",
        "shape",
        "source",
        "since",
        "duplicate of",
        "output columns",
    ]
    for line in table(header, rows):
        w(line)
    w("")


def _web(payload: dict[str, Any], w: Any) -> None:
    """Write both apps' web items and the classification of its items."""
    w("## Web pages and API endpoints")
    w("")
    rows = [
        [
            f"`{row['key']}`",
            row["class"],
            ", ".join(f"`{h}`" for h in row["here"]) or "-",
            row["phase"] or "-",
            row["note"],
        ]
        for row in payload["web"]["classified"]
    ]
    for line in table(["its item", "class", "here", "phase", "note"], rows):
        w(line)
    w("")
    w("This app's items:")
    w("")
    rows = [
        [r["kind"], r["method"], f"`{r['path']}`", f"`{r['file']}:{r['line']}`"]
        for r in payload["web"]["here"]
    ]
    for line in table(["kind", "method", "path", "where"], rows):
        w(line)
    w("")


def _rules(payload: dict[str, Any], w: Any) -> None:
    """Write the column rules with their hit counts."""
    w("## Column rules")
    w("")
    w("Each column's class, phase and note are its rule's; a rest rule takes every column of its")
    w("kinds no other rule matches, and must take exactly the number it expects.")
    w("")
    rows = [
        [
            f"`{r['id']}`",
            r["class"],
            r["hits"],
            r.get("expect", "-") if r.get("rest") else "-",
            r.get("phase", "") or "-",
            str(r.get("note", "")).strip(),
        ]
        for r in payload["rules"]
    ]
    for line in table(["rule", "class", "columns", "rest rule expects", "phase", "note"], rows):
        w(line)
    w("")
