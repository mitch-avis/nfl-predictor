"""Render ``PARITY.md`` from the parity check's payload."""

from __future__ import annotations

from collections import Counter
from typing import Any

from report_text import number, season_ranges, table

LISTED = 50


def render(payload: dict[str, Any], rules: dict[str, Any], records: list[dict[str, Any]]) -> str:
    """Return the Markdown report."""
    out: list[str] = []
    w = out.append
    w("<!-- markdownlint-disable -->")
    w("<!-- Generated file: wide tables and verbatim code cells; lint the generator. -->")
    w("")
    w("# Play-by-play parity with nfl-sos-ratings (generated)")
    w("")
    w("Generated by `.venv/bin/python .agents/sos_port/parity.py`; do not edit by hand. Every")
    w("mismatching team-game, with its values and causes, is in `parity.json` (`mismatches`); the")
    w("judged pairs and the causes' rules and evidence come from `parity.yaml`.")
    w("")
    _summary(payload, records, w)
    _pairs(payload, w)
    _causes(payload, rules, w)
    _coverage(payload, w)
    _sources(payload, w)
    _listing(records, w)
    w("## Failures")
    w("")
    failures = payload["failures"]
    kinds = Counter(f["what"] for f in failures)
    if not failures:
        w("None.")
    for what, count in sorted(kinds.items()):
        w(f"- {what}: {count}")
        w("")
        for failure in [f for f in failures if f["what"] == what][:LISTED]:
            w(f"  - {failure['detail']}")
        if count > LISTED:
            w(f"  - ... {count - LISTED} more in `parity.json` (`failures`)")
    w("")
    return "\n".join(out)


def _summary(payload: dict[str, Any], records: list[dict[str, Any]], w: Any) -> None:
    """Write the headline counts."""
    seasons = sorted(int(s) for s in payload["seasons"])
    statuses = Counter(r["status"] for r in records)
    compared = sum(p["compared"] for p in payload["pairs"])
    checkout = payload["sos_checkout"]
    w("## Summary")
    w("")
    pairs = len(payload["pairs"])
    w(f"- Seasons: {season_ranges(seasons)} ({len(seasons)}); judged pairs: {pairs}.")
    w(f"- Pair values compared (team-games times pairs): {compared}.")
    w(
        f"- Mismatching pair values: {len(records)}; explained: {statuses['explained']}; "
        f"provisional (hold only with the scramble stand-in): {statuses['provisional']}; "
        f"unexplained: {statuses['unexplained']}."
    )
    unexplained = [r for r in records if r["status"] == "unexplained"]
    flag_bound = sum(1 for r in unexplained if r["flagless_plays"])
    w(
        f"- Unexplained pair values in team-games with plays only the `qb_scramble` flag can "
        f"classify (rush attempts coded as pass plays without a dropback flag): {flag_bound} of "
        f"{len(unexplained)}."
    )
    w(f"- Scramble flag used: {', '.join(payload['scramble_flag'])}.")
    idle = [cause for cause, entry in payload["causes"].items() if not entry["team_games"]]
    w(f"- Causes that explain no team-game: {', '.join(f'`{c}`' for c in idle) or 'none'}.")
    w(f"- Failures: {len(payload['failures'])}.")
    changed = checkout["output_code_changed_since_build"] or "nothing"
    w(
        f"- nfl-sos-ratings at `{checkout['frozen_commit'][:7]}` (checkout HEAD "
        f"`{checkout['checkout_head'][:7]}`); its data built from "
        f"`{checkout['data_build_commit']}`, output code changed since: {changed}."
    )
    codes = ", ".join(f"{k} -> {v}" for k, v in payload["team_code_map"].items()) or "none"
    w(f"- Team codes read in this repository's spelling: {codes}.")
    w(f"- Input files read (sha256 in `parity.json`, `inputs`): {len(payload['inputs'])}.")
    w("")


def _pairs(payload: dict[str, Any], w: Any) -> None:
    """Write the judged pairs table."""
    w("## Judged pairs")
    w("")
    w("`here` is arithmetic over this repository's two play-by-play aggregates, `there` over its")
    w(
        "game logs. Counts must be equal; sums and rates within the tolerance "
        f"({payload['tolerance']})."
    )
    w("")
    rows = [
        [
            f"`{p['id']}`",
            f"`{p['ours']}`",
            f"`{p['theirs']}`",
            p["kind"],
            p["compared"],
            p["mismatched"],
            p["explained"],
            p["provisional"],
            p["unexplained"],
            ", ".join(f"`{c}`" for c in p["causes"]) or "-",
        ]
        for p in payload["pairs"]
    ]
    header = [
        "pair",
        "here",
        "there",
        "kind",
        "compared",
        "mismatched",
        "explained",
        "provisional",
        "unexplained",
        "causes allowed",
    ]
    for line in table(header, rows):
        w(line)
    w("")


def _causes(payload: dict[str, Any], rules: dict[str, Any], w: Any) -> None:
    """Write one section per cause."""
    w("## Causes")
    w("")
    w("A team-game counts under every cause combination that makes it match with the fewest")
    w('causes. "Explained by it": the combination holds without the stand-in\'s scrambles; "only')
    w('with the stand-in": it needs them; "another cause also matches": a different combination')
    w("of the same size matches too. The size columns are this repository's value minus the other")
    w("repository's, before any adjustment.")
    w("")
    for cause_id, entry in payload["causes"].items():
        rule = rules["causes"][cause_id]
        w(f"### {entry['name']} (`{cause_id}`)")
        w("")
        w(f"- There: {rule['there']}")
        w(f"- Here: {rule['here']}")
        w(f"- Adjustment: {rule['adjustment']}")
        w(
            f"- Team-games explained (alone or with another cause): {entry['team_games']}; "
            f"games: {entry['games']}; seasons: {season_ranges(entry['seasons'])}."
        )
        if "listed" in entry:
            w(f"- Games: {', '.join(entry['listed']) or 'none'}.")
        if "cached_la_values" in entry:
            left = entry["cached_la_values"]
            w(f"- `LA` values left in the cached play-by-play team columns: {left}.")
        w("")
        if entry["columns"]:
            rows = [
                [
                    f"`{pair}`",
                    stats["team_games"],
                    stats["explained"],
                    stats["provisional"],
                    stats["shared_with_another_cause"],
                    season_ranges(stats["seasons"]),
                    number(stats["signed_diff_sum"]),
                    number(stats["abs_diff_sum"]),
                    number(stats["max_abs_diff"]),
                ]
                for pair, stats in entry["columns"].items()
            ]
            header = [
                "pair",
                "team-games",
                "explained by it",
                "only with the stand-in",
                "another cause also matches",
                "seasons",
                "here minus there, total",
                "absolute total",
                "largest",
            ]
            for line in table(header, rows):
                w(line)
            w("")
        for row in payload["evidence"][cause_id]:
            status = "holds" if row["held"] else "FAILS"
            lines = ", ".join(str(n) for n in row["lines"]) or "none"
            w(
                f"- Evidence {status}: {row['repo']} `{row['path']}` /{row['pattern']}/ "
                f"{row['expect']} (lines: {lines})"
            )
        w("")


def _coverage(payload: dict[str, Any], w: Any) -> None:
    """Write the per-season keys and coverage table."""
    w("## Coverage and team-game keys")
    w("")
    rows = []
    for season, report in payload["seasons"].items():
        keys, coverage = report["keys"], report["coverage"]
        rows.append(
            [
                season,
                coverage["played_games"],
                keys["both"],
                keys["ours_only"],
                keys["theirs_only"],
                ", ".join(coverage["games_without_play_by_play"]) or "-",
                ", ".join(report["one_team_games"]) or "-",
                report["scramble_flag"],
            ]
        )
    header = [
        "season",
        "played games",
        "team-games on both sides",
        "here only",
        "there only",
        "games without play-by-play",
        "one-team games (cached team columns)",
        "scramble flag",
    ]
    for line in table(header, rows):
        w(line)
    w("")


def _sources(payload: dict[str, Any], w: Any) -> None:
    """Write every game-log column with its source and the pair that judges it."""
    judged: dict[str, list[str]] = {}
    for pair in payload["pairs"]:
        for name in pair["theirs"].replace("*", " ").replace("/", " ").split():
            judged.setdefault(name, []).append(pair["id"])
    sources = payload["game_log_sources"]
    counts = Counter(entry["source"] for entry in sources.values())
    w("## Game-log columns by source")
    w("")
    w("Read from its code at the frozen commit (`sos_sources.py`). Only play-by-play columns can")
    w("be judged; the others are listed with their source.")
    w("")
    for source, count in sorted(counts.items()):
        w(f"- {source}: {count}")
    w("")
    rows = [
        [f"`{column}`", entry["source"], entry["via"], ", ".join(judged.get(column, [])) or "-"]
        for column, entry in sources.items()
    ]
    for line in table(["column", "source", "code", "judged by"], rows):
        w(line)
    w("")


def _listing(records: list[dict[str, Any]], w: Any) -> None:
    """List the first unexplained and provisional team-games."""
    for status in ("unexplained", "provisional"):
        chosen = [r for r in records if r["status"] == status]
        w(f"## {status.capitalize()} team-games ({len(chosen)})")
        w("")
        if not chosen:
            w("None.")
            w("")
            continue
        by_pair = Counter((r["pair"], r["season"]) for r in chosen)
        rows = [[f"`{pair}`", season, count] for (pair, season), count in sorted(by_pair.items())]
        for line in table(["pair", "season", "team-games"], rows):
            w(line)
        w("")
        rows = [
            [
                r["season"],
                r["game_id"],
                r["team"],
                f"`{r['pair']}`",
                number(r["ours"]),
                number(r["theirs"]),
                ", ".join(r["causes"]) or "-",
                r["flagless_plays"],
            ]
            for r in chosen[:LISTED]
        ]
        w(f"First {min(LISTED, len(chosen))}:")
        w("")
        header = [
            "season",
            "game",
            "team",
            "pair",
            "here",
            "there",
            "causes",
            "plays only the flag can classify",
        ]
        for line in table(header, rows):
            w(line)
        w("")
