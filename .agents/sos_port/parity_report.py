"""Render ``PARITY.md`` from the parity check's payload."""

from __future__ import annotations

from collections import Counter
from typing import Any

from report_text import number, season_ranges, table

LISTED = 50


def render(payload: dict[str, Any], rules: dict[str, Any], records: list[dict[str, Any]]) -> str:
    """Return the Markdown report."""
    out: list[str] = []
    w = out.append
    w("<!-- markdownlint-disable -->")
    w("<!-- Generated file: wide tables and verbatim code cells; lint the generator. -->")
    w("")
    w("# Play-by-play parity with nfl-sos-ratings (generated)")
    w("")
    w("Generated by `PYTHONDONTWRITEBYTECODE=1 .venv/bin/python .agents/sos_port/parity.py`; do")
    w("not edit by hand. Every mismatching team-game, with its values and the causes that make it")
    w("match, is in `parity_attributions.parquet` (unexplained ones also in `parity.json`,")
    w("`unexplained`); the judged pairs and the causes' rules and evidence come from")
    w("`parity.yaml`.")
    w("")
    _summary(payload, records, w)
    _pairs(payload, w)
    _causes(payload, rules, w)
    _coverage(payload, w)
    _sources(payload, w)
    _listing(records, w)
    w("## Failures")
    w("")
    failures = payload["failures"]
    kinds = Counter(f["what"] for f in failures)
    if not failures:
        w("None.")
    for what, count in sorted(kinds.items()):
        w(f"- {what}: {count}")
        w("")
        for failure in [f for f in failures if f["what"] == what][:LISTED]:
            w(f"  - {failure['detail']}")
        if count > LISTED:
            w(f"  - ... {count - LISTED} more in `parity.json` (`failures`)")
    w("")
    return "\n".join(out)


def _summary(payload: dict[str, Any], records: list[dict[str, Any]], w: Any) -> None:
    """Write the headline counts."""
    seasons = sorted(int(s) for s in payload["seasons"])
    statuses = Counter(r["status"] for r in records)
    compared = sum(p["compared"] for p in payload["pairs"])
    checkout = payload["sos_checkout"]
    release = payload["causes"]["release_difference"]
    unexplained_games = {(r["season"], r["game_id"], r["team"]) for r in records if not r["causes"]}
    w("## Summary")
    w("")
    pairs = len(payload["pairs"])
    w(f"- Seasons: {season_ranges(seasons)} ({len(seasons)}); judged pairs: {pairs}.")
    w(f"- Pair values compared (team-games times pairs): {compared}.")
    w(
        f"- Mismatching pair values: {len(records)}; explained: {statuses['explained']}; "
        f"unexplained: {statuses['unexplained']} (in {len(unexplained_games)} team-games)."
    )
    w(
        f"- Snapshot of the play-by-play it read: {release.get('seasons_identical', 0)} of "
        f"{release.get('seasons_compared', 0)} seasons equal to this repository's cache row by row "
        f"on every cached column ({release.get('plays_compared', 0)} plays); "
        f"{', '.join(f'`{c}`' for c in payload['snapshot']['extra_columns'])} attached from it by "
        "row position."
    )
    idle = [cause for cause, entry in payload["causes"].items() if not entry["team_games"]]
    w(f"- Causes that explain no team-game: {', '.join(f'`{c}`' for c in idle) or 'none'}.")
    w(f"- Failures: {len(payload['failures'])}.")
    changed = checkout["output_code_changed_since_build"] or "nothing"
    w(
        f"- nfl-sos-ratings at `{checkout['frozen_commit'][:7]}` (checkout HEAD "
        f"`{checkout['checkout_head'][:7]}`); its data built from "
        f"`{checkout['data_build_commit']}`, output code changed since: {changed}."
    )
    codes = ", ".join(f"{k} -> {v}" for k, v in payload["team_code_map"].items()) or "none"
    w(f"- Team codes read in this repository's spelling: {codes}.")
    w(f"- Input files read (sha256 in `parity.json`, `inputs`): {len(payload['inputs'])}.")
    w("")


def _pairs(payload: dict[str, Any], w: Any) -> None:
    """Write the judged pairs table."""
    w("## Judged pairs")
    w("")
    w("`here` is arithmetic over this repository's two play-by-play aggregates, `there` over its")
    w(
        "game logs. Counts must be equal; sums and rates within the tolerance "
        f"({payload['tolerance']})."
    )
    w("")
    rows = [
        [
            f"`{p['id']}`",
            f"`{p['ours']}`",
            f"`{p['theirs']}`",
            p["kind"],
            p["compared"],
            p["mismatched"],
            p["explained"],
            p["unexplained"],
            ", ".join(f"`{c}`" for c in p["causes"]) or "-",
        ]
        for p in payload["pairs"]
    ]
    header = [
        "pair",
        "here",
        "there",
        "kind",
        "compared",
        "mismatched",
        "explained",
        "unexplained",
        "causes allowed",
    ]
    for line in table(header, rows):
        w(line)
    w("")


def _causes(payload: dict[str, Any], rules: dict[str, Any], w: Any) -> None:
    """Write one section per cause: what it explains, and its own effect."""
    w("## Causes")
    w("")
    w("Attribution: a team-game counts under a cause when a combination with the fewest causes")
    w('that includes it makes the team-game match; "alone" when the cause by itself does, and')
    w('"another combination also matches" when a different combination of the same size does too.')
    w("Effect: the cause's adjustment applied alone to every team-game, adjusted value minus")
    w("unadjusted, on the side it adjusts: this repository's, or the other's for an undone repair.")
    w("")
    for cause_id, entry in payload["causes"].items():
        rule = rules["causes"][cause_id]
        w(f"### {entry['name']} (`{cause_id}`)")
        w("")
        w(f"- There: {rule['there']}")
        w(f"- Here: {rule['here']}")
        w(f"- Adjustment: {rule['adjustment']}")
        w(
            f"- Team-games it explains (alone or with another cause): {entry['team_games']}; "
            f"games: {entry['games']}; seasons: {season_ranges(entry['seasons'])}."
        )
        _cause_details(entry, w)
        w("")
        if entry["columns"]:
            rows = [
                [
                    f"`{pair}`",
                    stats["team_games"],
                    stats["alone"],
                    stats["shared_with_another_cause"],
                    season_ranges(stats["seasons"]),
                ]
                for pair, stats in entry["columns"].items()
            ]
            header = ["pair", "team-games", "alone", "another combination also matches", "seasons"]
            for line in table(header, rows):
                w(line)
            w("")
        if entry["effect"]:
            rows = [
                [
                    f"`{name}`",
                    stats["team_games_changed"],
                    number(stats["adjusted_minus_unadjusted"]),
                    number(stats["absolute"]),
                    season_ranges(stats["seasons"]),
                ]
                for name, stats in entry["effect"].items()
            ]
            header = [
                "value",
                "team-games changed",
                "adjusted minus unadjusted",
                "absolute",
                "seasons",
            ]
            for line in table(header, rows):
                w(line)
            w("")
        for row in payload["evidence"][cause_id]:
            status = "holds" if row["held"] else "FAILS"
            lines = ", ".join(str(n) for n in row["lines"]) or "none"
            w(
                f"- Evidence {status}: {row['repo']} `{row['path']}` /{row['pattern']}/ "
                f"{row['expect']} (lines: {lines})"
            )
        w("")


def _cause_details(entry: dict[str, Any], w: Any) -> None:
    """Write the extra facts some causes carry."""
    if "listed" in entry:
        w(f"- Games: {', '.join(entry['listed']) or 'none'}.")
    if "flagged_plays_left_out_here" in entry:
        parts = [
            f"{play_type} {stats['plays']} ({season_ranges(stats['seasons'])})"
            for play_type, stats in entry["flagged_plays_left_out_here"].items()
        ]
        w(f"- Flagged plays the play-type filter leaves out, by play type: {'; '.join(parts)}.")
    if "wiped_out_plays" in entry:
        wiped = entry["wiped_out_plays"]
        runs = f"{number(wiped['rush'])} ({number(wiped['rush_epa'])} EPA)"
        passes = f"{number(wiped['pass'])} ({number(wiped['pass_epa'])} EPA)"
        texts = ", ".join(
            f"{name.replace('_', ' ')} {number(count)}"
            for name, count in entry.get("unflagged_no_plays", {}).items()
        )
        w(
            f"- Plays recorded as `no_play`: {number(wiped['plays'])}, of them "
            f"{number(wiped['without_penalty_flag'])} without the penalty flag (by their play "
            f"text: {texts or '-'}); with the rush flag still set: {runs}; with the pass flag: "
            f"{passes}; with the dropback flag: {number(wiped['qb_dropback'])}."
        )
    if "carries_without_rush_attempt" in entry:
        kinds = ", ".join(
            f"{kind} {number(count)}"
            for kind, count in entry["carries_without_rush_attempt"].items()
        )
        w(f"- Carries here without the `rush_attempt` flag, by play type: {kinds or 'none'}.")
    if "carries_from_rush_attempts" in entry:
        carries = {key: number(value) for key, value in entry["carries_from_rush_attempts"].items()}
        w(
            f"- Carries here today: {carries['today']}. Its designed-run rule (`rush_attempt` and "
            "not `two_point_attempt`, `qb_scramble` or `qb_kneel`) would add "
            f"{carries['with_flag_added']} and remove {carries['with_flag_removed']}. Without "
            f"`~qb_scramble` it would add {carries['without_flag_added']} (scrambles: "
            f"{carries['without_flag_added_scrambles']}; dropbacks here: "
            f"{carries['without_flag_added_dropbacks']}, of them scrambles: "
            f"{carries['without_flag_added_scramble_dropbacks']}) and remove "
            f"{carries['without_flag_removed']}."
        )
    if "cached_la_values" in entry:
        left = entry["cached_la_values"]
        w(f"- `LA` values left in the cached play-by-play team columns: {left}.")
    if "plays_compared" in entry:
        w(
            f"- Plays compared: {entry['plays_compared']}; seasons equal row by row: "
            f"{entry['seasons_identical']} of {entry['seasons_compared']}; games repeating a "
            f"`play_id`: {entry['games_repeating_a_play_id']}; rows equal on every cached column "
            f"to another row: {entry['rows_equal_to_another_row']} in "
            f"{entry['groups_of_equal_rows']} groups, of them differing in `qb_scramble`: "
            f"{entry['groups_of_equal_rows_differing_in_qb_scramble']}."
        )


def _coverage(payload: dict[str, Any], w: Any) -> None:
    """Write the per-season snapshot, keys and coverage table."""
    w("## Snapshot, coverage and team-game keys")
    w("")
    rows = []
    for season, report in payload["seasons"].items():
        keys, coverage, snapshot = report["keys"], report["coverage"], report["snapshot"]
        rows.append(
            [
                season,
                f"`{snapshot['file']}`",
                snapshot["identical_to_cache"],
                coverage["played_games"],
                keys["both"],
                keys["ours_only"],
                keys["theirs_only"],
                ", ".join(coverage["games_without_play_by_play"]) or "-",
                ", ".join(report["one_team_games"]) or "-",
            ]
        )
    header = [
        "season",
        "snapshot file",
        "equal to the cache",
        "played games",
        "team-games on both sides",
        "here only",
        "there only",
        "games without play-by-play",
        "games whose cached penalty and touchdown teams name one team",
    ]
    for line in table(header, rows):
        w(line)
    w("")


def _sources(payload: dict[str, Any], w: Any) -> None:
    """Write every game-log column with its source and the pair that judges it."""
    judged: dict[str, list[str]] = {}
    for pair in payload["pairs"]:
        for name in pair["theirs"].replace("*", " ").replace("/", " ").split():
            judged.setdefault(name, []).append(pair["id"])
    sources = payload["game_log_sources"]
    counts = Counter(entry["source"] for entry in sources.values())
    w("## Game-log columns by source")
    w("")
    w("Read from its code at the frozen commit (`sos_sources.py`). Only play-by-play columns can")
    w("be judged; the others are listed with their source.")
    w("")
    for source, count in sorted(counts.items()):
        w(f"- {source}: {count}")
    w("")
    rows = [
        [f"`{column}`", entry["source"], entry["via"], ", ".join(judged.get(column, [])) or "-"]
        for column, entry in sources.items()
    ]
    for line in table(["column", "source", "code", "judged by"], rows):
        w(line)
    w("")


def _listing(records: list[dict[str, Any]], w: Any) -> None:
    """List the unexplained team-games."""
    chosen = [r for r in records if r["status"] == "unexplained"]
    w(f"## Unexplained team-games ({len(chosen)})")
    w("")
    if not chosen:
        w("None.")
        w("")
        return
    rows = [
        [
            r["season"],
            r["game_id"],
            r["team"],
            f"`{r['pair']}`",
            number(r["ours"]),
            number(r["theirs"]),
        ]
        for r in chosen[:LISTED]
    ]
    for line in table(["season", "game", "team", "pair", "here", "there"], rows):
        w(line)
    w("")
