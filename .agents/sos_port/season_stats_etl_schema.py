"""Write the columns and types every full build of each season statistics table has.

Run from the repository root (single-threaded, about a minute; nothing is written but the module
below and a temporary directory under ``~/scratch``):

    .venv/bin/python .agents/sos_port/season_stats_etl_schema.py [--check]

It builds every season of 1999-2026 from the snapshot of the nflreadpy cache that
``nfl-sos-ratings`` read (``snapshot_cache.py``), with every source, through the ETL's season
statistics step's inputs (``SeasonStatsBuild.season_inputs``) and the package's builders, before
the step conforms anything; the rating columns come from frames of null ratings, typed as the
ratings build's. It then checks that every season's build of a table has the same columns in the
same order, and each column one type in every season, apart from one known difference:
``qb_game_logs.week`` is the play-by-play's ``Int32`` in a season without snap counts (before
2013) and ``Int64`` once the snap counts join, and is written as ``Int32``, the published files'
type, in every season. Any other difference stops the script.

It writes ``src/nfl_predictor/utils/polars/season_stats_schema.py``, the reference the step
conforms every table to (``season_stats_build.conform_table``), in ruff's format. With
``--check`` it writes nothing and exits 1 if the module differs from what it would write.
"""

from __future__ import annotations

import os

for _variable in (
    "OPENBLAS_NUM_THREADS",
    "OMP_NUM_THREADS",
    "MKL_NUM_THREADS",
    "POLARS_MAX_THREADS",
):
    os.environ.setdefault(_variable, "1")

import argparse
import sys
import tempfile
from pathlib import Path

import polars as pl

sys.path.insert(0, str(Path(__file__).resolve().parent))

import snapshot_cache  # a sibling module, importable once its dir is on the path

from nfl_predictor import constants
from nfl_predictor.season_stats import season as season_tables
from nfl_predictor.utils import polars_utils
from nfl_predictor.utils.polars import nflverse_sources, ratings_build, season_stats_build

HERE = Path(__file__).resolve().parent
MODULE = HERE.parents[1] / "src" / "nfl_predictor" / "utils" / "polars" / "season_stats_schema.py"
FIRST_SEASON = 1999
LAST_SEASON = 2026
# The one column whose type differs between seasons, and the type it is written as.
KNOWN_DIFFERENCES = {("qb_game_logs", "week"): pl.Int32()}
_NO_TEAM_RATINGS = pl.DataFrame(
    schema={
        "team": pl.String(),
        **dict.fromkeys(season_tables.TEAM_RATING_INPUT_COLUMNS[1:], pl.Float64()),
    }
)
_NO_QB_RATINGS = pl.DataFrame(
    schema={
        "qb_id": pl.String(),
        **dict.fromkeys(season_tables.QB_RATING_INPUT_COLUMNS[1:], pl.Float64()),
    }
)
_HEADER = '''"""The columns and types of every season statistics table, as a full build writes them.

Generated by ``.agents/sos_port/season_stats_etl_schema.py`` from the builds of every season of
{first}-{last} with every source, on the snapshot of the nflreadpy cache ``nfl-sos-ratings`` read;
do not edit by hand. Every season's full build of a table has these columns, in this order, with
these types, apart from ``qb_game_logs.week``: the play-by-play's ``Int32`` in a season without
snap counts and ``Int64`` once they join, it is the published files' ``Int32`` here. The ETL's
season statistics step conforms every table to its schema
(``season_stats_build.conform_table``), so a table built without a source, or without an opponent
profile, keeps every column, null where the missing part fills it.
"""

import polars as pl

SEASON_STATS_SCHEMAS: dict[str, pl.Schema] = {{
'''
_FOOTER = """}

__all__ = ["SEASON_STATS_SCHEMAS"]
"""


def _season_schemas(
    build: season_stats_build.SeasonStatsBuild, season: int
) -> dict[str, pl.Schema]:
    """Return the schema of every table of one season's full build, before any conforming."""
    inputs = build.season_inputs(season)
    tables = season_tables.build_season_tables(
        season_tables.build_season_games(inputs),
        inputs.pbp,
        team_ratings=_NO_TEAM_RATINGS,
        qb_ratings=_NO_QB_RATINGS,
    ).tables()
    return {kind: table.schema for kind, table in tables.items()}


def reference_schemas(seasons: list[int]) -> dict[str, pl.Schema]:
    """Return every table's schema across ``seasons``' full builds.

    Raises:
        SystemExit: If a season lacks a table, a table's columns differ between seasons, or a
            column's type differs between seasons other than as ``KNOWN_DIFFERENCES`` allows.

    """
    snapshot_cache.block_downloads()
    files = snapshot_cache.find_snapshot_files()
    by_season: dict[int, dict[str, pl.Schema]] = {}
    with tempfile.TemporaryDirectory(
        prefix="season_stats_schema_", dir=Path.home() / "scratch"
    ) as directory:
        cache = Path(directory) / "nflreadpy"
        snapshot_cache.write_cache(files, cache, list(range(FIRST_SEASON, seasons[-1] + 1)))
        constants.NFLREADPY_CACHE_DIR = cache
        constants.DATA_PATH = cache.parent
        options = {"cache_dir": cache, "current_season": snapshot_cache.CURRENT_SEASON}
        loaded = ratings_build.load_ratings_sources(
            seasons[-1],
            pbp_df=nflverse_sources.repair_one_team_pbp_games(
                polars_utils.load_pbp(seasons, **options), **options
            ),
            schedule_df=polars_utils.load_schedule(seasons, **options),
            current_season=snapshot_cache.CURRENT_SEASON,
            force_refresh=False,
        )
        if loaded is None:
            message = "the snapshot cache has no play-by-play"
            raise SystemExit(message)
        build = season_stats_build.SeasonStatsBuild(
            season_stats_build.load_season_stats_sources(
                seasons, loaded, current_season=snapshot_cache.CURRENT_SEASON, force_refresh=False
            )
        )
        for season in seasons:
            by_season[season] = _season_schemas(build, season)
    return {
        kind: _reference(kind, [tables.get(kind) for tables in by_season.values()], seasons)
        for kind in season_stats_build.SEASON_STATS_KINDS
    }


def _reference(kind: str, schemas: list[pl.Schema | None], seasons: list[int]) -> pl.Schema:
    """Return one table's schema across the seasons' builds, refusing any unknown difference."""
    present = [schema for schema in schemas if schema is not None]
    if len(present) != len(seasons):
        message = f"{kind}: {len(seasons) - len(present)} seasons have no table"
        raise SystemExit(message)
    names = present[0].names()
    if any(schema.names() != names for schema in present):
        message = f"{kind}: the columns or their order differ between seasons"
        raise SystemExit(message)
    columns: dict[str, pl.DataType] = {}
    for name in names:
        types = {str(schema[name]) for schema in present}
        if (kind, name) in KNOWN_DIFFERENCES:
            columns[name] = KNOWN_DIFFERENCES[kind, name]
        elif len(types) == 1:
            columns[name] = present[0][name]
        else:
            message = f"{kind}.{name}: types differ between seasons: {sorted(types)}"
            raise SystemExit(message)
    return pl.Schema(columns)


def _dtype_code(dtype: pl.DataType) -> str:
    """Return the Polars code of a simple type, such as ``pl.Int64()``.

    Raises:
        SystemExit: For a type with parameters (a list, struct or datetime), which no table has.

    """
    text = repr(dtype)
    if not text.isidentifier():
        message = f"the type {text} has parameters; render it by hand"
        raise SystemExit(message)
    return f"pl.{text}()"


def render(reference: dict[str, pl.Schema], seasons: list[int]) -> str:
    """Return the module's source, in ruff's format."""
    lines = [_HEADER.format(first=seasons[0], last=seasons[-1])]
    for kind, schema in reference.items():
        lines.append(f'    "{kind}": pl.Schema(\n        {{\n')
        lines.extend(
            f'            "{name}": {_dtype_code(dtype)},\n' for name, dtype in schema.items()
        )
        lines.append("        }\n    ),\n")
    lines.append(_FOOTER)
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    """Write the module, or with ``--check`` compare it; return 1 when it is out of date."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)
    seasons = list(range(FIRST_SEASON, LAST_SEASON + 1))
    source = render(reference_schemas(seasons), seasons)
    if arguments.check:
        current = MODULE.read_text(encoding="utf-8") if MODULE.exists() else ""
        status = "up to date" if current == source else "out of date"
        sys.stdout.write(f"{MODULE.name}: {status}\n")
        return 0 if current == source else 1
    MODULE.write_text(source, encoding="utf-8")
    sys.stdout.write(f"wrote {MODULE} ({sum(len(s) for s in source.splitlines())} characters)\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
